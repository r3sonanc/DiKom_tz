# L4: def объявляет функцию; аннотации str и tuple описывают типы концов ребра и результата.
def edge_key(a: str, b: str) -> tuple[str, str]:
    # L5: Возвращает концы ребра по алфавиту: A–B и B–A получают один ключ.
    return (a, b) if a <= b else (b, a)

# L7: Начинает функцию расстояния от точки (x, y) до отрезка от A до B.
def segment_distance(x: float, y: float, ax: float, ay: float,
                     # L8: Принимает координаты второго конца B; результат — вещественное расстояние.
                     bx: float, by: float) -> float:
    # L9: Находит вектор от A к B, отдельно по горизонтали и вертикали.
    dx, dy = bx - ax, by - ay
    # L10: Вычисляет квадрат длины отрезка, чтобы делить без лишнего извлечения корня.
    length_squared = dx * dx + dy * dy
    # L11: При нулевой длине берёт начало; иначе начинает ограничивать коэффициент проекции.
    t = 0.0 if length_squared == 0 else max(
        # L12: Проецирует точку на прямую и ограничивает коэффициент t диапазоном от 0 до 1.
        0.0, min(1.0, ((x - ax) * dx + (y - ay) * dy) / length_squared)
    # L13: Закрывает max: проекция остаётся внутри отрезка, включая его концы.
    )
    # L14: hypot вычисляет расстояние от точки до найденной ближайшей точки отрезка.
    return math.hypot(x - ax - t * dx, y - ay - t * dy)

